// Generates shape_weights_rows.hpp from the frozen shape_weights.hpp.
// Each weight array is re-declared as [rows][P] with the SAME element order
// (flat index = row*P + j), so the MAC stage can fully partition the P
// columns and address them by row without a divide-by-P. Biases and
// multipliers are not copied; the kernel uses the frozen header for those.
// Build/run on the server: g++ -std=c++14 -I<fixture> gen_rows.cpp && ./a.out > shape_weights_rows.hpp
#include <cstdio>
#include <cstdint>
#include "shape_weights.hpp"

template<int N, int P>
static void emit(const char *name, const int8_t (&w)[N]) {
    static_assert(N % P == 0, "P must divide N");
    std::printf("static const int8_t %s[%d][%d] = {\n", name, N / P, P);
    for (int r = 0; r < N / P; r++) {
        std::printf("  {");
        for (int j = 0; j < P; j++) std::printf("%d%s", int(w[r * P + j]), j + 1 < P ? "," : "");
        std::printf("}%s\n", r + 1 < N / P ? "," : "");
    }
    std::printf("};\n");
}

int main() {
    std::printf("// Generated by gen_rows.cpp from the frozen shape_weights.hpp. Do not edit.\n");
    std::printf("#pragma once\n#include <cstdint>\nnamespace shape {\n");
    emit<72, 9>("weight0_rows", shape::weight0);
    emit<1152, 36>("weight1_rows", shape::weight1);
    emit<3456, 36>("weight2_rows", shape::weight2);
    emit<6912, 18>("weight3_rows", shape::weight3);
    emit<131072, 16>("weight4_rows", shape::weight4);
    emit<2048, 8>("weight5_rows", shape::weight5);
    std::printf("}\n");
    return 0;
}
