`timescale 1ns / 1ps
// Reconfigurable module rm_cnn: the fused-block CNN engine (hls_cnn/cnn_top) behind
// the frozen RP boundary (pynq_dfx/scripts/rp_boundary.tcl). Port names/widths are
// exactly the shell_i/rp_accel pins of the routed static shell.
//   S_AXI_CTRL  8-bit AXI4-Lite -> cnn_top s_axi_ctrl (0x00 ap_ctrl, 0x04 GIE, 0x08 IER,
//               0x0C ISR, 0x10 mem base, 0x18 first, 0x20 count; see the HLS report)
//   M_AXI_MEM   cnn_top m_axi_gmem, 64-bit data, 32-bit address, ID 0
//   irq         cnn_top interrupt (ap_done, enabled through GIE/IER)
// Everything runs on ctrl_clk (100 MHz); fast_clk is unused.
module rm_cnn_top (
    input  wire        ctrl_clk,
    input  wire        ctrl_resetn,
    input  wire        fast_clk,
    input  wire        fast_resetn,
    output wire        irq,

    input  wire [7:0]  S_AXI_CTRL_awaddr,
    input  wire        S_AXI_CTRL_awvalid,
    output wire        S_AXI_CTRL_awready,
    input  wire [31:0] S_AXI_CTRL_wdata,
    input  wire [3:0]  S_AXI_CTRL_wstrb,
    input  wire        S_AXI_CTRL_wvalid,
    output wire        S_AXI_CTRL_wready,
    output wire [1:0]  S_AXI_CTRL_bresp,
    output wire        S_AXI_CTRL_bvalid,
    input  wire        S_AXI_CTRL_bready,
    input  wire [7:0]  S_AXI_CTRL_araddr,
    input  wire        S_AXI_CTRL_arvalid,
    output wire        S_AXI_CTRL_arready,
    output wire [31:0] S_AXI_CTRL_rdata,
    output wire [1:0]  S_AXI_CTRL_rresp,
    output wire        S_AXI_CTRL_rvalid,
    input  wire        S_AXI_CTRL_rready,

    output wire [5:0]  M_AXI_MEM_awid,
    output wire [31:0] M_AXI_MEM_awaddr,
    output wire [7:0]  M_AXI_MEM_awlen,
    output wire [2:0]  M_AXI_MEM_awsize,
    output wire [1:0]  M_AXI_MEM_awburst,
    output wire [3:0]  M_AXI_MEM_awcache,
    output wire [2:0]  M_AXI_MEM_awprot,
    output wire [3:0]  M_AXI_MEM_awqos,
    output wire        M_AXI_MEM_awvalid,
    input  wire        M_AXI_MEM_awready,
    output wire [63:0] M_AXI_MEM_wdata,
    output wire [7:0]  M_AXI_MEM_wstrb,
    output wire        M_AXI_MEM_wlast,
    output wire        M_AXI_MEM_wvalid,
    input  wire        M_AXI_MEM_wready,
    input  wire [5:0]  M_AXI_MEM_bid,
    input  wire [1:0]  M_AXI_MEM_bresp,
    input  wire        M_AXI_MEM_bvalid,
    output wire        M_AXI_MEM_bready,
    output wire [5:0]  M_AXI_MEM_arid,
    output wire [31:0] M_AXI_MEM_araddr,
    output wire [7:0]  M_AXI_MEM_arlen,
    output wire [2:0]  M_AXI_MEM_arsize,
    output wire [1:0]  M_AXI_MEM_arburst,
    output wire [3:0]  M_AXI_MEM_arcache,
    output wire [2:0]  M_AXI_MEM_arprot,
    output wire [3:0]  M_AXI_MEM_arqos,
    output wire        M_AXI_MEM_arvalid,
    input  wire        M_AXI_MEM_arready,
    input  wire [5:0]  M_AXI_MEM_rid,
    input  wire [63:0] M_AXI_MEM_rdata,
    input  wire [1:0]  M_AXI_MEM_rresp,
    input  wire        M_AXI_MEM_rlast,
    input  wire        M_AXI_MEM_rvalid,
    output wire        M_AXI_MEM_rready
);
    // Single master, one ID: HP2 returns whatever ID it gets, so drive 0.
    assign M_AXI_MEM_awid = 6'd0;
    assign M_AXI_MEM_arid = 6'd0;

    cnn_top u_cnn (
        .ap_clk(ctrl_clk),
        .ap_rst_n(ctrl_resetn),
        .interrupt(irq),

        .m_axi_gmem_AWVALID(M_AXI_MEM_awvalid),
        .m_axi_gmem_AWREADY(M_AXI_MEM_awready),
        .m_axi_gmem_AWADDR(M_AXI_MEM_awaddr),
        .m_axi_gmem_AWID(),
        .m_axi_gmem_AWLEN(M_AXI_MEM_awlen),
        .m_axi_gmem_AWSIZE(M_AXI_MEM_awsize),
        .m_axi_gmem_AWBURST(M_AXI_MEM_awburst),
        .m_axi_gmem_AWLOCK(),
        .m_axi_gmem_AWCACHE(M_AXI_MEM_awcache),
        .m_axi_gmem_AWPROT(M_AXI_MEM_awprot),
        .m_axi_gmem_AWQOS(M_AXI_MEM_awqos),
        .m_axi_gmem_AWREGION(),
        .m_axi_gmem_AWUSER(),
        .m_axi_gmem_WVALID(M_AXI_MEM_wvalid),
        .m_axi_gmem_WREADY(M_AXI_MEM_wready),
        .m_axi_gmem_WDATA(M_AXI_MEM_wdata),
        .m_axi_gmem_WSTRB(M_AXI_MEM_wstrb),
        .m_axi_gmem_WLAST(M_AXI_MEM_wlast),
        .m_axi_gmem_WID(),
        .m_axi_gmem_WUSER(),
        .m_axi_gmem_ARVALID(M_AXI_MEM_arvalid),
        .m_axi_gmem_ARREADY(M_AXI_MEM_arready),
        .m_axi_gmem_ARADDR(M_AXI_MEM_araddr),
        .m_axi_gmem_ARID(),
        .m_axi_gmem_ARLEN(M_AXI_MEM_arlen),
        .m_axi_gmem_ARSIZE(M_AXI_MEM_arsize),
        .m_axi_gmem_ARBURST(M_AXI_MEM_arburst),
        .m_axi_gmem_ARLOCK(),
        .m_axi_gmem_ARCACHE(M_AXI_MEM_arcache),
        .m_axi_gmem_ARPROT(M_AXI_MEM_arprot),
        .m_axi_gmem_ARQOS(M_AXI_MEM_arqos),
        .m_axi_gmem_ARREGION(),
        .m_axi_gmem_ARUSER(),
        .m_axi_gmem_RVALID(M_AXI_MEM_rvalid),
        .m_axi_gmem_RREADY(M_AXI_MEM_rready),
        .m_axi_gmem_RDATA(M_AXI_MEM_rdata),
        .m_axi_gmem_RLAST(M_AXI_MEM_rlast),
        .m_axi_gmem_RID(1'b0),
        .m_axi_gmem_RUSER(1'b0),
        .m_axi_gmem_RRESP(M_AXI_MEM_rresp),
        .m_axi_gmem_BVALID(M_AXI_MEM_bvalid),
        .m_axi_gmem_BREADY(M_AXI_MEM_bready),
        .m_axi_gmem_BRESP(M_AXI_MEM_bresp),
        .m_axi_gmem_BID(1'b0),
        .m_axi_gmem_BUSER(1'b0),

        .s_axi_ctrl_AWVALID(S_AXI_CTRL_awvalid),
        .s_axi_ctrl_AWREADY(S_AXI_CTRL_awready),
        .s_axi_ctrl_AWADDR(S_AXI_CTRL_awaddr[5:0]),
        .s_axi_ctrl_WVALID(S_AXI_CTRL_wvalid),
        .s_axi_ctrl_WREADY(S_AXI_CTRL_wready),
        .s_axi_ctrl_WDATA(S_AXI_CTRL_wdata),
        .s_axi_ctrl_WSTRB(S_AXI_CTRL_wstrb),
        .s_axi_ctrl_ARVALID(S_AXI_CTRL_arvalid),
        .s_axi_ctrl_ARREADY(S_AXI_CTRL_arready),
        .s_axi_ctrl_ARADDR(S_AXI_CTRL_araddr[5:0]),
        .s_axi_ctrl_RVALID(S_AXI_CTRL_rvalid),
        .s_axi_ctrl_RREADY(S_AXI_CTRL_rready),
        .s_axi_ctrl_RDATA(S_AXI_CTRL_rdata),
        .s_axi_ctrl_RRESP(S_AXI_CTRL_rresp),
        .s_axi_ctrl_BVALID(S_AXI_CTRL_bvalid),
        .s_axi_ctrl_BREADY(S_AXI_CTRL_bready),
        .s_axi_ctrl_BRESP(S_AXI_CTRL_bresp)
    );
endmodule
